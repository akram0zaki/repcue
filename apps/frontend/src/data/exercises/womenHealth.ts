/**
 * Helper to align with your multi-catalog pattern in generalFitness.ts
 */
function createExercise(
  exerciseData: Omit<
    Exercise,
    'updated_at' | 'created_at' | 'deleted' | 'version' | 'dirty' | 'op' | 'synced_at' | 'owner_id'
  > & { id: string }
): Exercise {
  return {
    ...exerciseData,
    updated_at: new Date().toISOString(),
    created_at: new Date().toISOString(),
    deleted: false,
    version: 1,
    dirty: 0,
  };
}

