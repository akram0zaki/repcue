/**
 * Check for and apply service worker updates immediately
 */
export const forceUpdateServiceWorker = async (): Promise<void> => {
  try {
    if (!('serviceWorker' in navigator)) {
      throw new Error('Service worker not supported');
    }

    const registration = await navigator.serviceWorker.ready;
    
    logger.log('🔍 Checking for service worker updates...');
    await registration.update();
    
    if (registration.waiting) {
      logger.log('🚀 Activating waiting service worker...');
      registration.waiting.postMessage({ type: 'SKIP_WAITING' });
      
      // Wait for controller change
      return new Promise((resolve) => {
        navigator.serviceWorker.addEventListener('controllerchange', () => {
          logger.log('✅ Service worker updated and activated');
          window.location.reload();
          resolve();
        });
      });
    } else {
      logger.log('ℹ️ No service worker updates available');
    }
  } catch (error) {
    logger.error('❌ Service worker update failed:', error);
    throw error;
  }
};

/**
 * Show install prompt for PWA
 */
export const setupInstallPrompt = (): Promise<boolean> => {
  return new Promise((resolve) => {
    let deferredPrompt: BeforeInstallPromptEvent | null = null;

    window.addEventListener('beforeinstallprompt', (e) => {
      // Prevent the mini-infobar from appearing on mobile
      e.preventDefault();
      deferredPrompt = e as BeforeInstallPromptEvent;

      logger.log('💡 PWA install prompt available');
      resolve(true);
    });

    // Handle install completion
    window.addEventListener('appinstalled', () => {
      logger.log('🎉 PWA was installed successfully');
      deferredPrompt = null;
    });

    // Timeout if no install prompt is available
    setTimeout(() => {
      if (!deferredPrompt) {
        resolve(false);
      }
    }, 3000);
  });
};

/**
 * Set up service worker message listener for communication with the custom SW
 */
const setupServiceWorkerMessageListener = (): void => {
  if (!('serviceWorker' in navigator)) {
    return;
  }

  navigator.serviceWorker.addEventListener('message', (event) => {
    const message: SWMessage = event.data;
    logger.log('📨 Received message from service worker:', message);

    switch (message.type) {
      case 'SW_UPDATED':
        logger.log('✅ Service worker updated successfully');
        swEventEmitter.emit('sw-updated', message);
        break;

      case 'SW_ACTIVATED':
        logger.log('🎯 Service worker activated and controlling all tabs');
        swEventEmitter.emit('sw-activated', message);
        break;

      case 'TRIGGER_VERSION_CHECK':
        logger.log('🔍 Service worker requesting version check');
        swEventEmitter.emit('trigger-version-check', message);
        break;

      case 'UPDATE_NOTIFICATION':
        logger.log('📬 Update notification from service worker');
        swEventEmitter.emit('update-notification', message);
        break;

      case 'VERSION_INFO':
        logger.log('ℹ️ Version info from service worker:', message.data);
        swEventEmitter.emit('version-info', message);
        break;

      default:
        logger.log('📨 Unknown message type from service worker:', message.type);
    }
  });
};

/**
 * Set up periodic update checks in coordination with the service worker
 */
const setupPeriodicUpdateCheck = (registration: ServiceWorkerRegistration): void => {
  // Check for updates every 30 minutes when the page is visible
  const checkInterval = 30 * 60 * 1000; // 30 minutes

  const checkForUpdates = async () => {
    if (document.hidden) {
      return; // Don't check when page is hidden
    }

    try {
      logger.log('🔍 Performing periodic service worker update check...');
      await registration.update();
    } catch (error) {
      logger.error('❌ Periodic update check failed:', error);
    }
  };

  // Set up interval
  const intervalId = setInterval(checkForUpdates, checkInterval);

  // Clear interval when page is unloaded
  window.addEventListener('beforeunload', () => {
    clearInterval(intervalId);
  });

  // Also check when page becomes visible
  document.addEventListener('visibilitychange', () => {
    if (!document.hidden) {
      // Delay slightly to avoid conflicts with other visibility handlers
      setTimeout(checkForUpdates, 1000);
    }
  });
};

/**
 * Send message to service worker
 */
export const sendMessageToServiceWorker = async (message: Partial<SWMessage>): Promise<unknown> => {
  if (!('serviceWorker' in navigator)) {
    throw new Error('Service worker not supported');
  }

  const registration = await navigator.serviceWorker.ready;

  if (!registration.active) {
    throw new Error('No active service worker');
  }

  return new Promise((resolve, reject) => {
    const messageChannel = new MessageChannel();

    messageChannel.port1.onmessage = (event) => {
      resolve(event.data);
    };

    // Timeout after 5 seconds
    const timeout = setTimeout(() => {
      reject(new Error('Service worker message timeout'));
    }, 5000);

    messageChannel.port1.onmessage = (event) => {
      clearTimeout(timeout);
      resolve(event.data);
    };

    registration.active!.postMessage(message, [messageChannel.port2]);
  });
};

/**
 * Get version information from service worker
 */
export const getServiceWorkerVersion = async (): Promise<string> => {
  try {
    const response = await sendMessageToServiceWorker({ type: 'GET_VERSION' });
    const versionResponse = response as { version?: string };
    return versionResponse.version || 'unknown';
  } catch (error) {
    logger.error('❌ Failed to get service worker version:', error);
    return 'unknown';
  }
};

/**
 * Enhanced update service worker with better coordination
 */
export const updateServiceWorkerCoordinated = async (registration: ServiceWorkerRegistration): Promise<void> => {
  if (!registration || !registration.waiting) {
    throw new Error('No service worker waiting to update');
  }

  logger.log('🚀 Starting coordinated service worker update...');

  return new Promise((resolve, reject) => {
    const timeout = setTimeout(() => {
      reject(new Error('Service worker update timeout'));
    }, 10000); // 10 second timeout

    // Listen for the controlling change event
    const handleControllerChange = () => {
      clearTimeout(timeout);
      navigator.serviceWorker.removeEventListener('controllerchange', handleControllerChange);
      logger.log('✅ Service worker update completed successfully');
      resolve();
    };

    navigator.serviceWorker.addEventListener('controllerchange', handleControllerChange);

    // Tell the waiting service worker to skip waiting and become active
    registration.waiting!.postMessage({ type: 'SKIP_WAITING' });

    // Emit event for other parts of the app
    swEventEmitter.emit('update-started', { registration });
  });
};
