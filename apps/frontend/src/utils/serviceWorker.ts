import logger from './logger'
/**
 * Service Worker registration utilities for RepCue PWA
 * Implements secure service worker management following OWASP guidelines
 */

export interface SWUpdateInfo {
  updateAvailable: boolean;
  registration?: ServiceWorkerRegistration;
}

export interface SWMessage {
  type: 'SW_UPDATED' | 'SW_ACTIVATED' | 'TRIGGER_VERSION_CHECK' | 'UPDATE_NOTIFICATION' | 'VERSION_INFO' | 'GET_VERSION';
  timestamp?: string;
  data?: unknown;
}

// Event callback types
type EventCallback = (...args: unknown[]) => void;

// Event emitter for service worker events
class ServiceWorkerEventEmitter {
  private listeners: Map<string, Set<EventCallback>> = new Map();

  on(event: string, callback: EventCallback): void {
    if (!this.listeners.has(event)) {
      this.listeners.set(event, new Set());
    }
    this.listeners.get(event)!.add(callback);
  }

  off(event: string, callback: EventCallback): void {
    const listeners = this.listeners.get(event);
    if (listeners) {
      listeners.delete(callback);
    }
  }

  emit(event: string, data?: unknown): void {
    const listeners = this.listeners.get(event);
    if (listeners) {
      listeners.forEach(callback => {
        try {
          callback(data);
        } catch (error) {
          logger.error(`Error in SW event listener for ${event}:`, error);
        }
      });
    }
  }
}

export const swEventEmitter = new ServiceWorkerEventEmitter();

interface BeforeInstallPromptEvent extends Event {
  readonly platforms: string[];
  readonly userChoice: Promise<{
    outcome: 'accepted' | 'dismissed';
    platform: string;
  }>;
  prompt(): Promise<void>;
}

/**
 * Register service worker and handle updates with enhanced event handling
 * Integrates with the RepCue update system for coordinated updates
 */
export const registerServiceWorker = (): Promise<SWUpdateInfo> => {
  return new Promise((resolve) => {
    // Only register service worker in production
    if (!('serviceWorker' in navigator) || import.meta.env.DEV) {
      logger.log('🔧 Service worker not registered in development mode');
      resolve({ updateAvailable: false });
      return;
    }

    // Set up service worker message listener before registration
    setupServiceWorkerMessageListener();

    window.addEventListener('load', async () => {
      try {
        logger.log('🚀 Registering service worker...');

        // Use the service worker generated by Vite PWA plugin
        const registration = await navigator.serviceWorker.register('/sw.js', {
          scope: '/',
          updateViaCache: 'none' // Always check for updates
        });

        logger.log('✅ Service worker registered successfully');

        // Enhanced update detection
        registration.addEventListener('updatefound', () => {
          const newWorker = registration.installing;

          if (newWorker) {
            logger.log('🔄 Service worker update found');
            swEventEmitter.emit('update-found', { registration, newWorker });

            newWorker.addEventListener('statechange', () => {
              logger.log(`🔄 SW state changed to: ${newWorker.state}`);

              if (newWorker.state === 'installed') {
                if (navigator.serviceWorker.controller) {
                  // New update available
                  logger.log('📦 New content available, waiting for activation');
                  swEventEmitter.emit('update-available', { registration });
                  resolve({
                    updateAvailable: true,
                    registration
                  });
                } else {
                  // Content is cached for offline use (first install)
                  logger.log('💾 Content is cached for offline use');
                  swEventEmitter.emit('first-install', { registration });
                  resolve({
                    updateAvailable: false,
                    registration
                  });
                }
              }

              if (newWorker.state === 'activated') {
                logger.log('✅ New service worker activated');
                swEventEmitter.emit('update-activated', { registration });
              }
            });
          }
        });

        // Enhanced controller change detection
        navigator.serviceWorker.addEventListener('controllerchange', () => {
          logger.log('🔄 Service worker controller changed');
          swEventEmitter.emit('controller-changed');
        });

        // Check if service worker is already controlling the page
        if (registration.active && !navigator.serviceWorker.controller) {
          logger.log('🔄 Service worker ready but not controlling, reloading...');
          window.location.reload();
        }

        // Set up periodic update checks
        setupPeriodicUpdateCheck(registration);

        resolve({
          updateAvailable: false,
          registration
        });

      } catch (error) {
        logger.error('❌ Service worker registration failed:', error);
        swEventEmitter.emit('registration-failed', { error });
        resolve({ updateAvailable: false });
      }
    });
  });
};

